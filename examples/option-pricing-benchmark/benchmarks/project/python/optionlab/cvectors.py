def _fast_cert(args):
    """(result, exception, locals at return, exit position) of optionlab.baw_admit.certificate without a tracer: the same
    function compiled again from its source with each `return X` turned into `return (X, locals(), <line>)` (the same
    statements in the same order, so the same binary64 values); used by the tie walks, whose cost a tracer multiplies."""
    import ast, inspect, textwrap
    from optionlab import baw_admit as ba
    if 'fn' not in _FAST:
        src=textwrap.dedent(inspect.getsource(ba.certificate));tree=ast.parse(src);first=ba.certificate.__code__.co_firstlineno
        class T(ast.NodeTransformer):
            def visit_Return(self,node):
                v=node.value or ast.Constant(None)
                call=ast.Call(func=ast.Name('locals',ast.Load()),args=[],keywords=[])
                return ast.copy_location(ast.Return(ast.Tuple([v,call,ast.Constant(node.lineno+first-1)],ast.Load())),node)
        tree=ast.fix_missing_locations(T().visit(tree));space=dict(vars(ba))
        exec(compile(tree,'<certificate fast>','exec'),space);_FAST['fn']=space['certificate'];_FAST['lines']=_return_lines(ba.certificate)
    from optionlab.models import RunDefect
    try:res,loc,line=_FAST['fn'](*args)
    except RunDefect:raise
    except Exception as e:return None,e,{},0
    return res,None,loc,_FAST['lines'].index(line)+1

def _cert_tie(name,args):
    """True when the call evaluates check `name` and its two sides are equal (the bound itself)."""
    res,exc,loc,pos=_fast_cert(args)
    if exc is not None or _CERT_NEEDS[name] not in loc:return False
    if name=='rate' and pos!=10:return False
    a,b=cert_sides(name,loc);return a==b

def _with_g(args,g):
    """args with LHS = g and RHS = 0.0 (g-hat = g exactly)."""
    return args[:7]+(g,0.0)+args[9:]

def _cert_get(args,var):
    """The walked quantity of a certificate argument tuple: |g-hat| (var 'g'), |d-hat| ('dh'), x0 ('x0') or K ('K')."""
    if var=='g':return abs(args[7]-args[8])
    if var=='dh':return abs((1.0-args[9]) if args[0]==0 else (-1.0-args[9]))
    if var=='x0':return args[1]
    return args[2]

def _cert_var(args,var,x):
    """args with the walked quantity set to x >= 0: LHS = x, RHS = 0 ('g'); b_i = 1 - x (call) or -1 - x (put), which keeps
    d-hat = x only when the subtraction is exact ('dh'); K = x ('K')."""
    if var=='g':return args[:7]+(x,0.0)+args[9:]
    if var=='dh':return args[:9]+((1.0-x) if args[0]==0 else (-1.0-x),)+args[10:]
    if var=='x0':return args[:1]+(x,)+args[2:]
    return args[:2]+(x,)+args[3:]

_CERT_FINE=(3,2,4,1,5)     # D_r, K, D_q, x0, v: arguments that move the sides of a check by at most a few ulps per ulp

def _cert_arg(args,index,x):return args[:index]+(x,)+args[index+1:]

def _cert_fine(name,args,span=1500):
    """args, or args with one fine argument (_CERT_FINE) moved by at most `span` ulps, whose check `name` is exactly at its
    bound (both sides equal, evaluated by the copied certificate text, _fast_cert); None when no such argument exists there."""
    if _cert_tie(name,args):return args
    for index in _CERT_FINE:
        if not (args[index]>0.0 and math.isfinite(args[index])):continue
        k=bits(args[index])
        for d in range(1,span+1):
            for m in (k-d,k+d):
                if m>0:
                    t=_cert_arg(args,index,fbits(m))
                    if _cert_tie(name,t):return t
    return None

def _cert_walk(name,base,var,budget):
    """A tie row near base for check `name` (None when not found): the adjacent pair where the check changes along the
    coarse argument `var` (adjacent_flip over it, upward and downward from its base value), then _cert_fine at each member
    of the pair. budget (a one-item list) bounds the number of fine scans (deterministic, no clock)."""
    x0=_cert_get(base,var)
    if budget[0]<=0 or not (x0>0.0 and math.isfinite(x0)):return None
    k0=_fast_cert(base)[2].get('k')
    def state(x):
        res,exc,loc,pos=_fast_cert(_cert_var(base,var,x))
        if exc is not None or _CERT_NEEDS[name] not in loc:return False
        if name=='rate':return pos==10 and loc['k']<=k0
        a,b=cert_sides(name,loc)
        return a>b if name in ('xlo','dlow','m') else a<=b
    if not state(x0):return None
    for step in (2.0,0.5):
        x=x0
        for _ in range(80):
            x=x*step
            if not (x>0.0 and math.isfinite(x)) or not state(x):break
        else:continue
        if not (x>0.0 and math.isfinite(x)):continue
        lo,hi=(x0,x) if x>x0 else (x,x0)
        try:a,b=adjacent_flip(state,lo,hi)
        except ValueError:continue
        if budget[0]<=0:return None
        budget[0]-=1
        for y in (a,b):
            hit=_cert_fine(name,_cert_var(base,var,y))
            if hit is not None:return hit
    return None

def _cert_state(name,args,k0=None):
    """True when the call evaluates check `name` and the check passes (for the rate test: exit 10 with k <= k0)."""
    res,exc,loc,pos=_fast_cert(args)
    if exc is not None or _CERT_NEEDS[name] not in loc:return False
    if name=='rate':return pos==10 and loc['k']<=k0
    a,b=cert_sides(name,loc)
    return a>b if name in ('xlo','dlow','m') else a<=b

def _cert_grid_tie(name,budget=12):
    """A tie row for check `name` from a grid of constructed calls (fix round 1b): x0 = K = 100, D_r = 0.96, D_q = 0.99,
    v = 0.04, Q = 2, d-hat = D (b_i = 1 - D) for 25 values of D from 1e-6 to 1e-3 and g-hat = r D for 13 values of r from
    1e-8 to 1e-2. Between two grid neighbours (in r) where the check passes at one and is evaluated and fails at the other,
    adjacent_flip over g-hat gives the adjacent pair, then _cert_fine at each member. None when no tie is found."""
    Ds=[10.0**(-6.0+0.125*i) for i in range(25)];rs=[10.0**(-8.0+0.5*i) for i in range(13)]
    mk=lambda D,g:(0,100.0,100.0,0.96,0.99,0.04,2.0,g,0.0,1.0-D,40)
    for D in Ds:
        prev=None
        for r in rs:
            g=r*D;st=_cert_state(name,mk(D,g))
            reached=_CERT_NEEDS[name] in _fast_cert(mk(D,g))[2]
            if prev is not None and prev[1]!=st and (reached or prev[2]):
                lo,hi=prev[0],g
                try:a,b=adjacent_flip(lambda x:_cert_state(name,mk(D,x)),lo,hi)
                except ValueError:a=b=None
                if a is not None:
                    budget-=1
                    for y in (a,b):
                        hit=_cert_fine(name,mk(D,y),span=600)
                        if hit is not None:return hit
                    if budget<=0:return None
            prev=(g,st,reached)
    return None

def _cert_line_tie(name,budget=20):
    """A tie row for check rho or the rate test (fix round 1b), on the constructed calls of _cert_grid_tie with D from 1e-6 to
    1e-3 in steps of 10**0.05 and g-hat from 1e-14 D upward by factors of 1.25: two neighbours where both calls evaluate the
    check and it changes (the rate test: the returned k changes), then adjacent_flip over g-hat and _cert_fine. None when not
    found."""
    mk=lambda D,g:(0,100.0,100.0,0.96,0.99,0.04,2.0,g,0.0,1.0-D,40)
    for i in range(61):
        D=10.0**(-6.0+0.05*i);prev=None;g=1e-14*D
        for _ in range(140):
            res,exc,loc,pos=_fast_cert(mk(D,g))
            cur=None
            if exc is None and _CERT_NEEDS[name] in loc and (name!='rate' or pos==10):
                cur=(g,loc['k'] if name=='rate' else cert_sides(name,loc)[0]<=cert_sides(name,loc)[1])
            if cur is not None and prev is not None and cur[1]!=prev[1]:
                k0=prev[1] if name=='rate' else None
                try:a,b=adjacent_flip(lambda x:_cert_state(name,mk(D,x),k0),prev[0],cur[0])
                except ValueError:a=None
                if a is not None:
                    budget-=1
                    for y in (a,b):
                        hit=_cert_fine(name,mk(D,y),span=600)
                        if hit is not None:return hit
                    if budget<=0:return None
            prev=cur;g=g*1.25
    return None

