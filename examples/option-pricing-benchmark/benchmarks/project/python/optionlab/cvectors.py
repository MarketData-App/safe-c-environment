def _first_double(pred,lo,hi):
    """The smallest double x in [lo, hi] (0 < lo < hi) with pred(x) true, for a pred that is false below a bound and true
    from it on (bisection over the bit patterns, which order positive doubles)."""
    a=bits(lo);b=bits(hi)
    while a<b:
        m=(a+b)//2
        if pred(struct.unpack('<d',struct.pack('<Q',m))[0]):b=m
        else:a=m+1
    return struct.unpack('<d',struct.pack('<Q',a))[0]

