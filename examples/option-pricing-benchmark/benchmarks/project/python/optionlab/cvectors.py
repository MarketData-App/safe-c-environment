def _near(pred,x,span=3000):
    """The double nearest to x (by bit distance, at most span ulps away) with pred true; ValueError when none."""
    k=bits(x)
    for d in range(span+1):
        for m in ((k,) if d==0 else (k-d,k+d)):
            if pred(fbits(m)):return fbits(m)
    raise ValueError('no point within %d ulps of %r'%(span,x))

