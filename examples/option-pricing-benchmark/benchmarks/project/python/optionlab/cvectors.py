def resolve_anchors(anchors=None,src_dir=None):
    """The audit locations of `anchors` (default CENSUS_ANCHORS) in the sources under src_dir (default: this package), as
    (frozenset {(type, 'file:line')}, [error]). Each anchor must match exactly once inside exactly one function of its name;
    every other result is an error with a named reason and no location: source-unreadable, scope-missing, scope-ambiguous,
    anchor-missing, anchor-ambiguous (with the matching lines), anchor-collision (two anchors on one location). Never a
    guess: the census gate fails on any error."""
    import ast
    base=Path(__file__).parent if src_dir is None else Path(src_dir)
    found=set();errors=[];sources={}
    for typ,name,scope,lines in (CENSUS_ANCHORS if anchors is None else anchors):
        label=f'{typ} {name} {scope}: {lines[0]}'
        if name not in sources:
            try:text=(base/name).read_text(encoding='utf-8');sources[name]=(text.splitlines(),ast.parse(text))
            except (OSError,UnicodeDecodeError,SyntaxError,ValueError):sources[name]=None
        if sources[name] is None:errors.append('source-unreadable '+label);continue
        text,tree=sources[name]
        defs=[n for n in ast.walk(tree) if isinstance(n,(ast.FunctionDef,ast.AsyncFunctionDef)) and n.name==scope]
        if len(defs)!=1:errors.append(('scope-missing ' if not defs else 'scope-ambiguous ')+label);continue
        lo,hi=defs[0].lineno,defs[0].end_lineno
        hits=[n for n in range(lo,hi-len(lines)+2) if all(text[n-1+i].strip()==t for i,t in enumerate(lines))]
        if not hits:errors.append('anchor-missing '+label);continue
        if len(hits)>1:errors.append('anchor-ambiguous '+label+' (lines '+', '.join(map(str,hits))+')');continue
        key=(typ,f'{name}:{hits[0]}')
        if key in found:errors.append(f'anchor-collision {label} (line {hits[0]})');continue
        found.add(key)
    return frozenset(found),errors

