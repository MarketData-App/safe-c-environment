def fbits(b):return struct.unpack('<d',struct.pack('<Q',b))[0]

def adjacent_flip(pred,lo,hi):
    """Adjacent positive doubles (a, b) in [lo, hi] (b = nextafter(a, inf)) with pred(a) != pred(b), by bisection over the bit
    patterns (which order positive doubles); pred(lo) != pred(hi) is required. For a pred that changes once on [lo, hi], a and
    b are the exact bound and its one-past value."""
    a=bits(lo);b=bits(hi);pa=pred(lo)
    if pred(hi)==pa:raise ValueError('pred does not change on [%r, %r]'%(lo,hi))
    while b-a>1:
        m=(a+b)//2
        if pred(fbits(m))==pa:a=m
        else:b=m
    return fbits(a),fbits(b)

_VARIANTS={}
def models_variant(old,new):
    """A namespace with optionlab.models executed again from its source text, `old` (exactly one occurrence) replaced by `new`.
    The bound searches read inner quantities of the engine this way, so they use the engine's own statements."""
    import inspect, types
    from optionlab import models
    key=(old,new)
    if key not in _VARIANTS:
        src=inspect.getsource(models)
        if src.count(old)!=1:raise ValueError('variant site not unique: '+old)
        space={'__name__':'optionlab_models_variant'}
        exec(compile(src.replace(old,new),'<models variant>','exec'),space)
        _VARIANTS[key]=types.SimpleNamespace(**space)
    return _VARIANTS[key]

