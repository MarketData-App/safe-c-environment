def _return_lines(fn):
    """The source lines of the return statements of fn in source order (the exit position is the index + 1)."""
    import ast, inspect, textwrap
    first=fn.__code__.co_firstlineno
    return sorted(n.lineno+first-1 for n in ast.walk(ast.parse(textwrap.dedent(inspect.getsource(fn)))) if isinstance(n,ast.Return))

def _traced(fn,args,watch=None,lines=None):
    """fn(*args) under sys.settrace: (result, exception, locals of that frame at its return, exit position (0 when fn
    raised), the argument dicts of every call of `watch` during the call)."""
    code=fn.__code__;wcode=watch.__code__ if watch is not None else None;box={'calls':[]}
    def local(frame,event,arg):
        if event=='return':box['locals']=dict(frame.f_locals);box['line']=frame.f_lineno
        return local
    def tracer(frame,event,arg):
        if event!='call':return None
        if frame.f_code is code and 'seen' not in box:box['seen']=True;return local
        if frame.f_code is wcode:box['calls'].append(dict(frame.f_locals))
        return None
    from optionlab.models import RunDefect
    old=sys.gettrace();sys.settrace(tracer)
    try:res,exc=fn(*args),None
    except RunDefect:raise
    except Exception as e:res,exc=None,e
    finally:sys.settrace(old)
    pos=0 if exc is not None else (lines or _return_lines(fn)).index(box['line'])+1
    return res,exc,box.get('locals',{}),pos,box['calls']

