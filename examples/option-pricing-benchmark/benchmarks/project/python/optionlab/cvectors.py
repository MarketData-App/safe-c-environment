PARTS={}
FORMAT_STYLE='--style=file:/src/.clang-format'

def part(name):
    def register(fn):PARTS[name]=fn;return fn
    return register

def bits(v):return struct.unpack('<Q',struct.pack('<d',float(v)))[0]
def lit(v):return 'UINT64_C(0x%016x)'%bits(v)
def lit_plain(v):
    """The bits as a plain unsigned literal (0x...U; up to 0xFFFFFFFF the type is unsigned int, larger values unsigned long on LP64; both convert exactly to uint64_t). Large parts use it:
    the clang AST dump of the AST gate records every macro expansion, and UINT64_C on thousands of literals passes the
    32 MiB limit of that dump. Earlier parts keep lit (their headers stay byte-identical)."""
    return '0x%016xU'%bits(v)

def render(name,fields,rows,preamble=True):
    """fields: [(c_type, member)], c_type 'uint64_t' for a double (bits) or 'int'; rows: lists of C literals."""
    s='pl_vec_'+name;u=s.upper()
    out=([f'/* Generated by optionlab.cvectors (part {name}) from the optionlab Python definitions; do not edit. */','#pragma once',
          '#include <stddef.h>','#include <stdint.h>',''] if preamble else [''])+[f'struct {s} {{']
    out+=[f'    {t} {m};' for t,m in fields]+['};','',f'static const struct {s} {u}[] = {{']
    out+=['    {'+', '.join(r)+'},' for r in rows]+['};',f'#define {u}_COUNT ((size_t){len(rows)})','']
    return '\n'.join(out)

def write_parts(out_dir,names):
    if shutil.which('clang-format') is None:raise RuntimeError('clang-format is required to write vector headers')
    out=Path(out_dir);written=[];counts={}
    for name in names:
        text,count=PARTS[name]()
        if text.startswith('{'):
            target=out/f'{name}.json';target.write_text(text,encoding='ascii')
        else:
            target=out/f'pl_vec_{name}.h';target.write_text(text,encoding='ascii')
            subprocess.run(['clang-format',FORMAT_STYLE,'-i',str(target)],check=True,timeout=120)
        written.append(target.name);counts[name]=count
    return written,counts

