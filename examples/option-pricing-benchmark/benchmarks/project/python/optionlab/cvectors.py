def _alo_case(site,force):
    """(CaseParams, context) of the C test-only pair (alo_plant_site, alo_force): the merged CaseParams fields for a value-mask
    site and a cap excess, the merged test-only context managers (SAFE_C_TEST_COUNTERS=1 inside the context only) for the
    persistent NaN and the inner bracket error. The contexts are entered here; the caller closes them with `with`."""
    import contextlib, os
    from unittest import mock
    from optionlab import alo
    from optionlab.params import CASE
    sites=alo_plant_sites();forces=alo_forces();kw={};stack=contextlib.ExitStack()
    if not (0<=site<=len(sites) and 0<=force<=len(forces)):raise ValueError('alo test parameters out of range')
    persistent=site>0 and sites[site-1]==ALO_PERSISTENT
    if persistent or force==1:stack.enter_context(mock.patch.dict(os.environ,{'SAFE_C_TEST_COUNTERS':'1'}))
    if persistent:stack.enter_context(alo.plant_nan('qdplus:66',persistent=True))
    elif site:kw['alo_plant_nan']=sites[site-1]
    if force==1:stack.enter_context(alo.force_inner_bracket_error())
    elif force:kw['alo_force_cap']=forces[force-1]
    return _replace(CASE,**kw),stack

def alo_outcome(call):
    """('value', call()) or ('defect', kind, site) of the models.AloRunDefect that call() raises: the one ALO record site of
    the vectors (A4R-03 allow-list PHASE2_RECORD_SITES); every other exception propagates to the caller."""
    from optionlab.models import AloRunDefect, RunDefect
    try:return ('value',call())
    except AloRunDefect as exc:return _alo_defect(exc)
    except RunDefect:raise

def _alo_defect(exc):return ('defect',exc.args[0],exc.site)

def _alo_trace(stats,eq,res):
    """ALO_TRACE_FIELDS of one engine evaluation: equation (0 FP_A, 1 FP_B, -1 when the mapping raised), the alo.Stats counts
    (zero when the engine did not run) and the site of a run defect: failed_check (1 + index in ALO_CHECK_SITES) for
    'alo-nan', failed_cap (1 + index in alo.CAPS) for 'alo-cap'."""
    from optionlab import alo
    fc=fk=0
    if res is not None and res[0]=='defect':
        if res[1]=='alo-nan':fc=ALO_CHECK_SITES.index(res[2])+1
        elif res[1]=='alo-cap':fk=tuple(alo.CAPS).index(res[2])+1
        else:raise ValueError('unknown ALO run defect '+str(res[1]))
    if stats is None:return (eq,0,0,0,0,0,0,0,fc,fk)
    return (eq,stats.qd_calls,stats.halley_max,stats.fallback_nodes,stats.fallback_max,stats.levels,stats.integrand,stats.guarded,fc,fk)

def alo_engine_outcome(row,site=0,force=0):
    """(status 0 OK, 1 order 5, 2 a Python raise; ALO_TRACE_FIELDS values; value) of alo.price (one engine evaluation: the
    mapping, the pre check, alo_equation and the engine) under the C pair (site, force). Order 5 is a ModelDefect: the pre
    check (AloPreCheck: failed_check 1, no engine statistics), a QuantLib or Boost error (AloEngineError), the inner QD+
    solver (AloInnerSolverError). A Python raise is an AloRunDefect (failed_check or failed_cap names its site) or a
    ZeroDivisionError or ValueError (read_back of a zero exponential, a side or T that the mapping refuses: equation -1)."""
    from optionlab import alo
    from optionlab.alo_equation import FP_A
    from optionlab.models import ModelDefect, RunDefect
    side,S,K,T,r,q,s=row;nan=math.nan
    prm,ctx=_alo_case(site,force)
    with ctx:
        try:_,_,_,s1,r_e,q_e,kind=alo.mapped_point(side,S,K,T,r,q,s)
        except RunDefect:raise
        except (ZeroDivisionError,ValueError):return 2,_alo_trace(None,-1,None),nan
        eq=0 if kind==FP_A else 1
        try:alo.pre_check(S,K,r_e,q_e,s1)
        except RunDefect:raise
        except ModelDefect:return 1,(eq,0,0,0,0,0,0,0,1,0),nan
        try:res=alo_outcome(lambda:alo.price(side,S,K,T,r,q,s,prm))
        except RunDefect:raise
        except ModelDefect:return 1,_alo_trace(alo.last_stats(),eq,None),nan
        except (ZeroDivisionError,ValueError):return 2,_alo_trace(alo.last_stats(),eq,None),nan
    st=alo.last_stats()
    if res[0]=='defect':return 2,_alo_trace(st,eq,res),nan
    return 0,_alo_trace(st,eq,None),res[1]

def alo_points(stencils):
    """Ruling 45 (I7.4): the stencil points that the chosen I2.6 stencils evaluate: S 2; vega 2 central or 1 forward; rho 2
    central or 1 one-sided; theta 1 (T - delta, or T + delta when forward)."""
    return 2+(2 if stencils['sigma'][0]=='central' else 1)+(2 if stencils['r'][0]=='central' else 1)+1

def alo_greeks_outcome(row,site=0,force=0):
    """(status 0 OK, 1 order 5, 2 a Python raise; band; flags; engine calls; values; stencil points; ALO_FORM_FIELDS) of the ALO branch of
    reference.price_and_greeks at sigma (Checker(tau_v), alo_pre, the price at sigma, reference.alo_greeks) with the counter
    ev of reference.evaluate: each greek point that passes the pre check (H17, I7.4; the price at sigma is not counted).
    Order 5: StencilUnresolved (flags 16), EngineDomain or a ModelDefect (flags 0). An OK row whose count differs from
    alo_points of its stencils stops the generator (ruling 45)."""
    from optionlab import reference
    from optionlab.models import ModelDefect, RunDefect
    side,S,K,T,r,q,s=row;ev=[0];box={};nan7=(math.nan,)*7
    prm,ctx=_alo_case(site,force)
    def run():
        box['check']=check=reference.Checker(reference.tau_v(S,K,T,r,q))
        value=reference._alo_engine(prm)(side,K,q);reference.alo_pre(side,S,K,T,r,q,s)
        p=check(value(S,T,r,s))
        return reference.alo_greeks(side,S,K,T,r,q,s,p,prm,value,check,ev)
    def band():return int(box['check'].band) if 'check' in box else 0
    none=(0,0,0,0,0)
    with ctx:
        try:res=alo_outcome(run)
        except RunDefect:raise
        except reference.StencilUnresolved:return 1,band(),16,ev[0],nan7,0,none
        except (reference.EngineDomain,ModelDefect):return 1,band(),0,ev[0],nan7,0,none
        except (ZeroDivisionError,ValueError):return 2,0,0,ev[0],nan7,0,none
    if res[0]=='defect':return 2,0,0,ev[0],nan7,0,none
    vals,flags,stencils=res[1];pts=alo_points(stencils)
    if ev[0]!=pts:raise ValueError('engine_evals differs from the chosen stencil points (ruling 45)')
    return 0,band(),flags,ev[0],vals,pts,alo_forms(stencils,T,prm)

ALO_FORM_FIELDS=('vega_form','rho_form','theta_form','rho_halved','theta_halved')
def alo_forms(stencils,T,prm):
    """ALO_FORM_FIELDS of the stencils that reference.alo_greeks chose: vega 1 central / 2 forward; rho 1 central / 2 forward /
    3 backward; theta 1 backward / 2 forward; rho_halved and theta_halved 1 when the chosen step is below the first step
    (h_r; min(1/365, T/2))."""
    vega={'central':1,'forward':2}[stencils['sigma'][0]];rho={'central':1,'forward':2,'backward':3}[stencils['r'][0]]
    theta={'backward':1,'forward':2}[stencils['T'][0]]
    return vega,rho,theta,int(stencils['r'][1]<prm.h_r),int(stencils['T'][1]<min(1.0/365.0,T/2.0))

_ALO_EVALUATE={}
def evaluate_alo_outcome(row,prm,site=0,force=0):
    """(status index, flags, defect, engine_evals, values) of reference.evaluate for alo under the C pair (site, force) with
    sigma_hi and kappa_cap of prm. A Python raise (AloRunDefect, ZeroDivisionError, ValueError) is defect 1 with status 0,
    flags 0, 0 evaluations and NaN values: the run fails (H19)."""
    from optionlab.reference import evaluate
    from optionlab.models import RunDefect
    from optionlab.contract import STATUSES
    key=(int(row[0]),)+tuple(bits(x) for x in row[1:])+(bits(prm.sigma_hi),bits(prm.kappa_cap),site,force)
    if key in _ALO_EVALUATE:return _ALO_EVALUATE[key]
    p,ctx=_alo_case(site,force);p=_replace(p,sigma_hi=prm.sigma_hi,kappa_cap=prm.kappa_cap)
    with ctx:
        try:res=alo_outcome(lambda:evaluate(tuple(row),'alo',p))
        except RunDefect:raise
        except (ZeroDivisionError,ValueError):res=None
    if res is None or res[0]=='defect':out=(0,0,1,0,(math.nan,)*7)
    else:
        st,vals,flags,ev=res[1];out=(STATUSES.index(st),flags,0,ev,tuple(vals))
    _ALO_EVALUATE[key]=out
    return out

