def alo_ts_samples(k,n,fc):
    """Indices of row k (length n, first complement index fc) in table alo_ts: every index of the tabulated rows 0-7; for a
    computed row (8-14) every 2**(k-6)-th index, the first three and last two indices and fc - 2 ... fc + 1."""
    if k<=7:return list(range(n))
    step=1<<(k-6)
    return sorted(set(range(0,n,step))|{0,1,2,n-2,n-1}|{j for j in range(fc-2,fc+2) if 0<=j<n})

FNV64_OFFSET=0xcbf29ce484222325;FNV64_PRIME=0x100000001b3
def alo_ts_digest(a,w):
    """The digest of one tanh-sinh row (ruling R-10c, T10B-TS-SAMPLE-01): 64-bit FNV-1a (offset basis 0xcbf29ce484222325,
    prime 0x100000001b3, modulo 2**64) over the bytes of the row in entry order: for each index j = 0 ... n - 1, the 8
    bytes of the IEEE-754 bit pattern of abscissa j, least significant byte first, then the 8 bytes of weight j. The C test
    recomputes it from pl_alo_ts_entry over every entry."""
    h=FNV64_OFFSET
    if len(a)!=len(w):raise ValueError('tanh-sinh row lengths differ')
    for x,y in zip(a,w):
        for v in (x,y):
            for b in bits(v).to_bytes(8,'little'):h=((h^b)*FNV64_PRIME)&0xFFFFFFFFFFFFFFFF
    return h

