/* tanh_sinh_detail::t_from_abscissa_complement(0.5) (alo._t_from_abscissa_complement,
 * tanh_sinh_detail.hpp:167-174): l = log(2 - x) - log(x), log((sqrt(l l + pi pi) + l) / pi). */
double pl_alo_ts_crossover(void) {
    const double x = 0.5;
    const double l = log(2.0 - x) - log(x);
    return log((sqrt(l * l + PL_ALO_PI * PL_ALO_PI) + l) / PL_ALO_PI);
}

/* h = 2^-level of a computed row (math.ldexp(1.0, -row)): exact halvings. */
static double row_step(int level) {
    double h = 1.0;
    for (int i = 0; i < level; i++) {
        h *= 0.5;
    }
    return h;
}

int pl_alo_ts_row_with(int level, double crossover, int *length, int *first_complement) {
    if (level < 0 || level >= PL_ALO_TS_ROWS) {
        return 1;
    }
    if (level < PL_ALO_TS_TABLE_ROWS) {
        *length = *(ts_lengths + level);
        *first_complement = *(ts_first_complements + level);
        return 0;
    }
    /* extend_refinements (tanh_sinh_detail.hpp:103-141): positions h, 3h, ... < t_max; the first
     * complement index counts the positions below t_crossover. The row has 3 * 2^level entries,
     * so the loop is bounded by that count. */
    const double h = row_step(level);
    const int bound = 3 << level;
    int n = 0;
    int fc = 0;
    for (int j = 0; j < bound + 1; j++) {
        const double pos = (double)(2 * j + 1) * h;
        if (!(pos < PL_ALO_TS_T_MAX)) {
            break;
        }
        if (pos < crossover) {
            fc++;
        }
        n++;
    }
    *length = n;
    *first_complement = fc;
    return 0;
}

int pl_alo_ts_entry_with(int level, int index, double crossover, double *abscissa, double *weight) {
    if (level < 0 || level >= PL_ALO_TS_ROWS || index < 0) {
        return 1;
    }
    if (level < PL_ALO_TS_TABLE_ROWS) {
        if (index >= *(ts_lengths + level)) {
            return 1;
        }
        const int at = *(ts_offsets + level) + index;
        *abscissa = *(ts_abscissas + at);
        *weight = *(ts_weights + at);
        return 0;
    }
    /* The bound test of pl_alo_ts_row_with without its scan: the positions (2j + 1) h increase
     * with j, so index < length exactly when index <= 3 * 2^level and its position is < t_max. */
    if (index > (3 << level)) {
        return 1;
    }
    const double pos = (double)(2 * index + 1) * row_step(level);
    if (!(pos < PL_ALO_TS_T_MAX)) {
        return 1;
    }
    if (pos < crossover) {
        *abscissa = tanh(PL_ALO_HALF_PI * sinh(pos));
    } else {
        const double u2 = PL_ALO_HALF_PI * sinh(pos);
        *abscissa = -(1.0 / (exp(u2) * cosh(u2)));
    }
    const double cs = cosh(PL_ALO_HALF_PI * sinh(pos));
    *weight = PL_ALO_HALF_PI * cosh(pos) / (cs * cs);
    return 0;
}

int pl_alo_ts_row(int level, int *length, int *first_complement) {
    return pl_alo_ts_row_with(level, pl_alo_ts_crossover(), length, first_complement);
}

int pl_alo_ts_entry(int level, int index, double *abscissa, double *weight) {
    return pl_alo_ts_entry_with(level, index, pl_alo_ts_crossover(), abscissa, weight);
}
